//! Saved frames: bytes written by THIS build must still open on a LATER one,
//! and a LATER build's frame must still open on this one.
//!
//! # The codec boundary a fixture is saved at
//!
//! `tests/peer_wire.rs`'s `a_frame_round_trips_and_a_short_buffer_asks_for_more`
//! already covers `encode_frame`/`decode_frame`: a `u16` length prefix around
//! whatever bytes it is given, with no field of its own and nothing in it
//! that changes as a message type grows a field. Fixturing that layer would
//! prove nothing an older build could ever get wrong. What DOES change
//! release to release is the JSON payload inside the frame, so every fixture
//! here is that payload's exact UTF-8 text: what a peer's Noise session
//! decrypts into before `serde_json` ever sees it. A byte-for-byte capture
//! of an encoded frame would be this same text with four more bytes glued on
//! the front, and reading it back would still mean stripping those four
//! bytes and handing the rest to `serde_json`, so the JSON text is the
//! payload this crate's forward-compatibility promise is actually about.
//!
//! # Every fixture here was written by the build in this worktree
//!
//! Each one is hand-composed to match a real value (never regenerated by
//! calling `serde_json::to_string` and saving the output: a fixture
//! produced that way proves only that this build agrees with itself). Every
//! address is inside a documentation range (RFC 5737 `192.0.2.0/24` and
//! `198.51.100.0/24`); every id, key and hash is an obviously fake
//! placeholder.
//!
//! # What "the version bumped past the one this build reads" means here
//!
//! Every field this crate might one day add already has `#[serde(default)]`,
//! so the wire crate's own struct types have nothing that a bumped VALUE
//! (as opposed to a bumped SHAPE) can make them refuse: a `Hello.proto` of
//! 99 still decodes, because the parse's job is to survive a newer build,
//! never to police one (see the crate's own module docs: "the PARSE never
//! fails on a value a newer build invented. The unknown arm keeps the parse
//! alive; the HANDLER refuses it"). The one place that sentence is backed by
//! a real, already-wired handler reachable without standing up a Noise
//! session is `StreamKind`: `peer_stream_gate_rows` (`src/peer/listener.rs`)
//! refuses an unknown stream kind by name, with `StreamRefusal::UnknownKind`,
//! before it ever reads a grant. `stream_header_unknown_kind.json` fixtures a
//! `StreamHeader` naming a kind number no build has assigned, standing in for
//! a stream kind a future release invents: the parse survives it and the
//! typed refusal, not a panic, is what stops it.

use tcr_peer_wire::{
    Caps, Hello, InstanceId, Knock, Lease, LeaseGrant, LeaseReceipt, LeaseRefusal, LeaseRequest,
    LeaseUnit, Lendable, NeighborBrief, PeerId, StreamHeader, StreamKind, Window,
};
use teamclaude_rs::peer::listener::{peer_stream_gate_rows, StreamRefusal};

/// `tests/fixtures/wire/<name>`, read as UTF-8 text.
fn fixture(name: &str) -> String {
    std::fs::read_to_string(
        concat!(env!("CARGO_MANIFEST_DIR"), "/tests/fixtures/wire/").to_string() + name,
    )
    .unwrap_or_else(|err| panic!("fixture {name} is readable: {err}"))
}

fn node_b() -> PeerId {
    PeerId::parse("QEXVQEXVQEXVQEXVQEXVQEXVQEXVQEXVQEXVQEXVQEXVQEXVQEXG")
        .expect("fixture node id b decodes")
}

fn node_c() -> PeerId {
    PeerId::parse("SK6CSK6CSK6CSK6CSK6CSK6CSK6CSK6CSK6CSK6CSK6CSK6CSK60")
        .expect("fixture node id c decodes")
}

/// A `Hello` with every optional field populated decodes to the exact value
/// this build wrote, byte for byte, field for field.
///
/// Watch it fail: change `"seq":42` to `"seq":43` in the fixture and this
/// assertion reports a mismatched `Hello`, not a panic.
#[test]
fn hello_full_decodes_to_the_expected_value() {
    let hello: Hello = serde_json::from_str(&fixture("hello_full.json"))
        .expect("hello_full.json decodes as a Hello");
    assert_eq!(
        hello,
        Hello {
            proto: 1,
            node: node_b(),
            label: "laptop-full".to_string(),
            seq: 42,
            caps: Caps {
                egress: true,
                forward: true,
                lends: true,
            },
            addrs: vec![
                "192.0.2.10:9600".to_string(),
                "198.51.100.20:9600".to_string()
            ],
            ttl_s: 60,
            lendable: Some(vec![Lendable {
                window: Window::FiveHour,
                unit: LeaseUnit::Fraction(0.25),
                accounts: 2,
            }]),
            hops_to_egress: Some(1),
            briefs: Some(vec![NeighborBrief {
                node: node_c(),
                caps: Caps {
                    egress: false,
                    forward: true,
                    lends: false,
                },
                addrs: vec!["198.51.100.21:9600".to_string()],
            }]),
            build_sha: Some("deadbeefcafef00d".to_string()),
            boot_id: Some(123_456_789),
            observed_you_at: Some("192.0.2.11:41000".to_string()),
        }
    );
}

