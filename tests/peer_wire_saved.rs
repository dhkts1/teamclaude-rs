/// A stream naming a kind number no build has assigned yet still parses (the
/// crate's own promise: an unknown arm keeps a mixed-build LAN's parse
/// alive), and the production handler, not a panic, is what refuses it.
///
/// Watch it fail two ways, both run by hand before this shipped: (a) change
/// `"kind":9999` to `"kind":1` (`StreamKind::Tunnel`) and the assertion on
/// the parsed value fails, because the fixture no longer names an unknown
/// kind; (b) comment out the `StreamKind::Unknown(_)` arm in
/// `crates/tcr-peer-wire/src/lib.rs`'s `From<u16> for StreamKind` so it
/// cannot represent 9999 at all, and `serde_json::from_str` itself fails
/// this test rather than reaching the handler assertion: the parse-survives
/// half breaks before the refuse half is ever exercised.
#[test]
fn stream_header_with_an_unassigned_kind_parses_and_is_refused_by_the_handler_not_a_panic() {
    let header: StreamHeader = serde_json::from_str(&fixture("stream_header_unknown_kind.json"))
        .expect("a stream header naming an unassigned kind still parses");
    assert_eq!(
        header,
        StreamHeader {
            kind: StreamKind::Unknown(9999),
            target: None,
            via: vec![],
            hops_remaining: 1,
            request_id: 1001,
        }
    );
    assert_eq!(
        peer_stream_gate_rows(&header, None),
        Err(StreamRefusal::UnknownKind(9999)),
        "the handler must refuse an unknown kind by name, before it ever reads a grant, and \
         must not panic reaching that refusal"
    );
}
